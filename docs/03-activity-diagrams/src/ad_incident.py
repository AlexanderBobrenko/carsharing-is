from swimlane import Diagram

D = Diagram([("Клиент", 300), ("Система каршеринга", 300), ("Менеджер проката", 560), ("Техник", 300), ("Страховая компания", 300)])
L, Rr = -140, 140   # колонки дорожки «Менеджер»: левая (особые ветки), правая (основной поток)

D.node('s', 'start', 0, 0)
D.node('c1', 'action', 0, 1, "Сообщает об инциденте,\nприкладывает фото")
D.node('s1', 'action', 1, 2, "Регистрирует инцидент,\nуведомляет менеджера")
D.node('m1', 'action', 2, 3, "Связывается с клиентом,\nуточняет обстоятельства", dx=Rr)
D.node('d1', 'decision', 2, 4, "Есть третьи лица\nили пострадавшие?\n(БП-26)", dx=Rr, w=250)
D.node('c2', 'action', 0, 4, "Вызывает ГИБДД,\nоформляет ДТП")
D.node('m2', 'action', 2, 5, "Определяет виновника\nпо доказательствам", dx=Rr)
D.node('d2', 'decision', 2, 6, "Вина клиента\nустановлена?", dx=Rr, w=250)
D.node('m3', 'action', 2, 6, "Закрывает инцидент\nбез начислений", dx=L)
D.node('e1', 'end', 2, 7, dx=L)
D.node('f1', 'bar', 2, 7, x1=(2, Rr), x2=(3, 0))
D.node('m4', 'action', 2, 8, "Проверяет обстоятельства:\nопьянение, бегство, нет\nоформления ДТП (БП-28)", dx=Rr)
D.node('t1', 'action', 3, 8, "Осматривает автомобиль,\nоценивает ущерб")
D.node('j1', 'bar', 2, 9, x1=(2, Rr), x2=(3, 0))
D.node('d3', 'decision', 2, 10, "Найдено\nисключение из\nстраховой защиты?", dx=Rr, w=250)
D.node('m6', 'action', 2, 11, "Начисляет долю клиента:\n15 000 ₽ или 15% ущерба;\nпередаёт данные страховой", dx=Rr)
D.node('i1', 'action', 4, 12, "Рассматривает\nстраховой случай")
D.node('d4', 'decision', 4, 13, "Страховой случай\nпризнан?", w=250)
D.node('i2', 'action', 4, 14, "Покрывает остальную\nстоимость ремонта")
D.node('m5', 'action', 2, 13, "Начисляет клиенту полный\nподтверждённый ущерб", dx=L)
D.node('s2', 'action', 1, 15, "Списывает начисление\nс карты клиента,\nзакрывает инцидент")
D.node('e2', 'end', 1, 16)

D.edge('s', 'c1')
D.edge('c1', 's1', out='r')
D.edge('s1', 'm1', out='r')
D.edge('m1', 'd1')
D.edge('d1', 'c2', 'да', out='l', inn='r')
D.edge('d1', 'm2', 'нет')
D.edge('c2', 'm2')
D.edge('m2', 'd2')
D.edge('d2', 'm3', 'нет', out='l', inn='r')
D.edge('m3', 'e1')
D.edge('d2', 'f1', 'да')
D.edge('f1', 'm4'); D.edge('f1', 't1')
D.edge('m4', 'j1'); D.edge('t1', 'j1')
D.edge('j1', 'd3')
D.edge('d3', 'm5', 'да', out='l', inn='t')
D.edge('d3', 'm6', 'нет')
D.edge('m6', 'i1', out='r')
D.edge('i1', 'd4')
D.edge('d4', 'i2', 'да')
D.edge('d4', 'm5', 'нет', out='l', inn='r')
D.edge('m5', 's2')
D.edge('i2', 's2', my=14.47)
D.edge('s2', 'e2')

if __name__ == '__main__':
    D.draw('ad-3-incident')
