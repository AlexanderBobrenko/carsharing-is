"""Генерация диаграмм состояний (UML State Machine) через Graphviz.
Запуск: python3 gen_states.py  -> *.dot и *.png в текущей папке (нужен пакет graphviz: `dot`)."""
import subprocess

FONT = 'Liberation Sans'

def render(name, states, edges, rankdir='TB', start_to=None, finals=(), title=None):
    L = ['digraph G {',
         f'  rankdir={rankdir}; nodesep=0.7; ranksep=0.85; pad=0.3; dpi=130; splines=true;',
         f'  node [fontname="{FONT}", fontsize=13, shape=box, style="rounded,filled", fillcolor="#e8f0fb", color="#1f3a5f", penwidth=1.5, margin="0.25,0.14"];',
         f'  edge [fontname="{FONT}", fontsize=11, color="#333333", arrowsize=0.9];']
    L.append('  __start [shape=circle, label="", width=0.25, style=filled, fillcolor=black, color=black];')
    L.append('  __end [shape=doublecircle, label="", width=0.22, style=filled, fillcolor=black, color=black];')
    for s in states:
        L.append(f'  "{s}";')
    L.append(f'  __start -> "{start_to[0]}" [label=" {start_to[1]} "];')
    for a, b, lab in edges:
        L.append(f'  "{a}" -> "{b}" [label=" {lab} "];')
    for f in finals:
        L.append(f'  "{f}" -> __end;')
    L.append('}')
    open(name + '.dot', 'w', encoding='utf-8').write('\n'.join(L))
    subprocess.run(['dot', '-Tpng', name + '.dot', '-o', name + '.png'], check=True)
    subprocess.run(['dot', '-Tsvg', name + '.dot', '-o', name + '.svg'], check=True)

